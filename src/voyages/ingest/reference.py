"""Build the reference tables from the .sav value labels.

Every coded field in the registry names a ``reference`` table. This
module collects the value labels for those fields from the three .sav
files and writes one CSV per reference to ``voyages/schema/reference/``.
The CSVs are regenerated by ``voyages build`` and committed so changes
show up in diffs. Never edit them by hand: fix the rules or overrides
here, or the curated inputs (``place_coordinates.csv``).

Each table keeps the original label verbatim in ``source_label`` and
adds ``label`` in project language (see CLAUDE.md).
"""

from __future__ import annotations

import csv
import re
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from voyages import schema
from voyages.config import raw_dir

REFERENCE_DIR = schema.REGISTRY_PATH.parent / "reference"
COORDINATES_CSV = REFERENCE_DIR / "curated" / "place_coordinates.csv"

SAV_FILES = {
    "transatlantic": "tastdb-exp-2020.sav",
    "intraamerican": "I-Am1.0.sav",
    "estimates": "2010-estimates-SPSS.sav",
}
# When datasets disagree on a label, the first one listed here wins and
# the other wording is kept in source_label_alt.
DATASET_PRIORITY = ("transatlantic", "intraamerican", "estimates")


# ----------------------------------------------------------------- labels
# Whole-label overrides, keyed by (reference, code). Used where a rule
# would read badly or where the source uses historical terms for people,
# which we quote rather than paraphrase.
LABEL_OVERRIDES: dict[tuple[str, int], str] = {
    ("african_origins", 1): "Enslaved people newly arrived from Africa (recorded as 'New Negroes')",
    ("african_origins", 2): (
        "Enslaved people already seasoned or held on plantations "
        "(recorded as 'Seasoned or plantation slaves')"
    ),
    ("african_origins", 9): "Recorded as 'Mulatto'",
    ("african_origins", 12): (
        "Enslaved people, newly arrived and seasoned (recorded as 'New and seasoned slaves')"
    ),
    (
        "african_origins",
        16,
    ): "Africans and Indigenous Americans (recorded as 'Negroes and Indians')",
    ("african_origins", 6): "Indigenous Americans (recorded as 'Indians')",
    ("outcomes_captives", 1): "Captives disembarked in the Americas",
    ("outcomes_captives", 2): "No captives embarked",
    ("outcomes_captives", 3): "Captives disembarked in Africa or Europe",
    ("outcomes_captives", 4): "Captives perished with the ship",
    ("outcomes_captives", 5): "Captives embarked, then transshipped or no further record",
    ("outcomes_captives", 6): "No information on captives",
    ("outcomes_captives", 7): "Captives embarked but not disembarked in Europe or the Americas",
    ("outcomes_owner", 1): "Delivered captives for the original owners",
    ("resistance", 1): "Insurrection by captives",
    ("resistance", 4): "'Cut-off' (meaning unclear: insurrection or attack from shore)",
    ("resistance", 5): "Three or more captives jumped overboard, went missing, or escaped",
    ("decades", 29): "1781-1790",
}

_RULES: list[tuple[str, str]] = [
    # "Captured by slaves" means the enslaved people on board seized the ship.
    (r"^(captured|taken) by slaves\b", "seized by the captives"),
    (r"\bslaves embarked\b", "captives embarked"),
    (r"\bembarkation of slaves\b", "embarkation of captives"),
    (r"\bduring slaving\b", "during the purchase of captives"),
    (r"\bslaving\b", "purchase of captives"),
    (r"\bslaver\b", "slaving vessel"),
    (r"\bslaves\b", "captives"),
    (r"\bslave\b", "captive"),
]


def project_label(text: str) -> str:
    """Rewrite a source label into project language (see CLAUDE.md)."""
    out = re.sub(r"\s+", " ", text).strip()
    for pat, repl in _RULES:
        out = re.sub(
            pat,
            lambda m, r=repl: r[0].upper() + r[1:] if m.group(0)[0].isupper() else r,
            out,
            flags=re.I,
        )
    return out


# ----------------------------------------------------------------- reading
@dataclass
class LabelSet:
    """All labels seen for one reference table, by code and dataset."""

    labels: dict[int, dict[str, str]] = field(default_factory=lambda: defaultdict(dict))
    used: dict[int, set[str]] = field(default_factory=lambda: defaultdict(set))


def _read(dataset: str, raw: Path, *, with_data: bool):
    import pyreadstat

    path = raw / SAV_FILES[dataset]
    if with_data:
        return pyreadstat.read_sav(path, apply_value_formats=False)
    return pyreadstat.read_sav(path, metadataonly=True)


def collect(raw: Path | None = None) -> dict[str, LabelSet]:
    """Gather labels (and codes actually used in the data) per reference."""
    raw = raw or raw_dir()
    reg = schema.load()
    out: dict[str, LabelSet] = defaultdict(LabelSet)
    for dataset in SAV_FILES:
        df, meta = _read(dataset, raw, with_data=True)
        cols = {c.upper(): c for c in meta.column_names}
        for f in reg.for_dataset(dataset):
            if not f.reference:
                continue
            col = cols[f.spss_name_in(dataset).upper()]
            ls = out[f.reference]
            vl = meta.variable_to_label.get(col)
            for code, lab in (meta.value_labels.get(vl, {}) if vl else {}).items():
                ls.labels[int(code)].setdefault(dataset, re.sub(r"\s+", " ", lab).strip())
            for code in df[col].dropna().unique():
                ls.used[int(code)].add(dataset)
    return out


def _pick(by_ds: dict[str, str]) -> tuple[str | None, str | None]:
    order = [d for d in DATASET_PRIORITY if d in by_ds]
    if not order:
        return None, None
    first = by_ds[order[0]]
    alt = next((by_ds[d] for d in order[1:] if by_ds[d] != first), None)
    return first, alt


# ----------------------------------------------------------------- tables
def coded_rows(ref: str, ls: LabelSet) -> list[dict]:
    rows = []
    for code in sorted(set(ls.labels) | set(ls.used)):
        src, alt = _pick(ls.labels.get(code, {}))
        datasets = sorted(set(ls.labels.get(code, {})) | ls.used.get(code, set()))
        if src is None:
            label, note = None, "code used in data, no label in source"
        else:
            label, note = LABEL_OVERRIDES.get((ref, code)) or project_label(src), None
        rows.append(
            {
                "code": code,
                "label": label,
                "source_label": src,
                "source_label_alt": alt,
                "datasets": ";".join(d for d in DATASET_PRIORITY if d in datasets),
                "used_in_data": code in ls.used,
                "note": note,
            }
        )
    return rows


def place_level(code: int) -> str:
    if code % 10000 == 0:
        return "broad_region"
    if code % 100 == 0:
        return "region"
    return "place"


def load_coordinates(path: Path = COORDINATES_CSV) -> dict[int, dict[str, str]]:
    if not path.exists():
        return {}
    with path.open(newline="", encoding="utf-8") as f:
        return {int(r["code"]): r for r in csv.DictReader(f)}


PLACE_COORD_COLUMNS = ("lat", "lon", "coord_source", "coord_precision", "coord_ref")


def place_rows(ls: LabelSet, coords: dict[int, dict[str, str]] | None = None) -> list[dict]:
    """Places with the port -> region -> broad region hierarchy.

    The hierarchy comes from the code digits (codebook p.30). Voyage-level
    region fields are kept as recorded and can differ from this default
    parent for places that changed jurisdiction.
    """
    coords = load_coordinates() if coords is None else coords
    rows = []
    for r in coded_rows("places", ls):
        code = r["code"]
        level = place_level(code)
        c = coords.get(code, {})
        # 99xxx codes ("undefined NNN", "wreck") sit outside the hierarchy:
        # there is no broad region 90000.
        outside = code >= 90000
        rows.append(
            {
                "code": code,
                "name": r["label"],
                "source_name": r["source_label"],
                "alt_name": r["source_label_alt"],
                "level": level,
                "region_code": code // 100 * 100 if level == "place" and not outside else None,
                "broad_region_code": None if outside else code // 10000 * 10000,
                "datasets": r["datasets"],
                "used_in_data": r["used_in_data"],
                **{k: (c.get(k) or None) for k in PLACE_COORD_COLUMNS},
                "note": r["note"],
            }
        )
    return rows


def write_csv(rows: list[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: ("" if v is None else v) for k, v in r.items()})


def build(raw: Path | None = None, out_dir: Path = REFERENCE_DIR) -> dict[str, int]:
    """Regenerate every reference CSV. Returns {table: row count}."""
    counts = {}
    for ref, ls in sorted(collect(raw).items()):
        rows = place_rows(ls) if ref == "places" else coded_rows(ref, ls)
        write_csv(rows, out_dir / f"{ref}.csv")
        counts[ref] = len(rows)
    return counts
