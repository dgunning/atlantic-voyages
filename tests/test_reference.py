"""Checks on the reference tables in src/voyages/schema/reference/.

The CSVs are generated by `voyages build` from the .sav value labels and
committed. Offline tests read the committed files. The full-data test
rebuilds them and checks the committed copies match, so a hand edit or a
stale file fails CI.
"""

import csv
import filecmp
import os
import re
from pathlib import Path

import pytest

from voyages import schema
from voyages.ingest import reference

REF = reference.REFERENCE_DIR


def read(name: str) -> list[dict[str, str]]:
    with (REF / f"{name}.csv").open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def references_in_registry() -> set[str]:
    return {f.reference for f in schema.load().fields if f.reference}


def test_every_registry_reference_has_a_table():
    for ref in references_in_registry():
        assert (REF / f"{ref}.csv").exists(), ref


@pytest.mark.parametrize("ref", sorted(references_in_registry()))
def test_codes_are_unique(ref):
    codes = [r["code"] for r in read(ref)]
    assert len(codes) == len(set(codes))


@pytest.mark.parametrize("ref", sorted(references_in_registry() - {"places"}))
def test_labels_follow_project_language(ref):
    # Source wording stays verbatim in source_label. Our label may quote it
    # ("recorded as '...'"), but must not otherwise use "slave(s)" as a noun.
    for r in read(ref):
        unquoted = re.sub(r"'[^']*'", "", r["label"])
        assert not re.search(r"\bslaves?\b", unquoted, re.I), (ref, r["code"], r["label"])
        assert r["label"] or r["note"], (ref, r["code"])


def test_outcome_label_example():
    # FATE 56: enslaved people on board seized the ship.
    row = next(r for r in read("outcomes") if r["code"] == "56")
    assert row["source_label"] == "Captured by slaves: ship did not reach the Americas"
    assert row["label"] == "Seized by the captives: ship did not reach the Americas"


def test_places_hierarchy_is_consistent():
    rows = read("places")
    codes = {int(r["code"]) for r in rows}
    for r in rows:
        code = int(r["code"])
        if code >= 90000:  # "undefined NNN", "wreck": outside the hierarchy
            assert not r["broad_region_code"]
            continue
        assert r["level"] == reference.place_level(code)
        assert int(r["broad_region_code"]) in codes, code
        if r["level"] == "place" and r["region_code"]:
            assert int(r["region_code"]) == code // 100 * 100


def test_known_ports():
    """Spot-check against the site's place list and modern coordinates.

    Ouidah ("Whydah") 6.36N 2.08E, Bonny 4.43N 7.17E, Kingston (Jamaica) 18.0N 76.8W.
    """
    places = {r["code"]: r for r in read("places")}
    for code, name, region, lat, lon in [
        ("60515", "Whydah", "60500", 6.37, 2.08),
        ("60605", "Bonny", "60600", 4.43, 7.17),
        ("35114", "Kingston", "35100", 18.0, -76.8),
    ]:
        p = places[code]
        assert p["name"] == name and p["region_code"] == region
        assert abs(float(p["lat"]) - lat) < 0.1 and abs(float(p["lon"]) - lon) < 0.1


def test_coordinates_are_traceable():
    places = {r["code"]: r for r in read("places")}
    with reference.COORDINATES_CSV.open(encoding="utf-8") as f:
        coords = list(csv.DictReader(f))
    assert len(coords) > 500
    for c in coords:
        p = places[c["code"]]
        assert p["level"] == "place", c["code"]
        assert -90 <= float(c["lat"]) <= 90 and -180 <= float(c["lon"]) <= 180
        assert (float(c["lat"]), float(c["lon"])) != (0.0, 0.0), c["code"]
        assert c["coord_source"] in ("slavevoyages", "geonames")
        assert c["coord_ref"], c["code"]
        if c["coord_source"] == "geonames":
            assert re.fullmatch(r"geonames:\d+", c["coord_ref"]), c["coord_ref"]
        assert c["coord_precision"] in ("place", "representative")
        # places.csv carries exactly the curated values
        assert (p["lat"], p["lon"], p["coord_source"]) == (c["lat"], c["lon"], c["coord_source"])


@pytest.mark.fulldata
@pytest.mark.skipif(not os.environ.get("VOYAGES_DATA_DIR"), reason="needs VOYAGES_DATA_DIR")
def test_committed_reference_tables_match_a_fresh_build(tmp_path: Path):
    reference.build(out_dir=tmp_path)
    for p in sorted(REF.glob("*.csv")):
        assert filecmp.cmp(p, tmp_path / p.name, shallow=False), p.name
