"""Build the reference tables from the .sav value labels.

Every coded field in the registry names a ``reference`` table. This
module collects the value labels for those fields from the three .sav
files and writes one CSV per reference to ``voyages/schema/reference/``.
The CSVs are regenerated by ``voyages build`` and committed so changes
show up in diffs. Never edit them by hand: fix the rules or overrides
here, or the curated inputs (``place_coordinates.csv``).

Each table keeps the original label verbatim in ``source_label`` and
adds ``label`` in project language (see CLAUDE.md).
"""

from __future__ import annotations

import csv
import math
import re
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from voyages import schema
from voyages.config import raw_dir

REFERENCE_DIR = schema.REGISTRY_PATH.parent / "reference"
COORDINATES_CSV = REFERENCE_DIR / "curated" / "place_coordinates.csv"

SAV_FILES = {
    "transatlantic": "tastdb-exp-2020.sav",
    "intraamerican": "I-Am1.0.sav",
    "estimates": "2010-estimates-SPSS.sav",
}
# When datasets disagree on a label, the first one listed here wins and
# the other wording is kept in source_label_alt.
DATASET_PRIORITY = ("transatlantic", "intraamerican", "estimates")


# ----------------------------------------------------------------- labels
# Whole-label overrides, keyed by (reference, code). Used where a rule
# would read badly or where the source uses historical terms for people,
# which we quote rather than paraphrase.
